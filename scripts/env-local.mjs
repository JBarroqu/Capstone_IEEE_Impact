// Writes the local Supabase values into the git-ignored .env.local, so nobody has to copy keys by hand.
// Run after `supabase start` (npm run db:start does this). Keys this script does not manage are kept.
import { execSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const file = process.argv[2] ? path.resolve(process.argv[2]) : path.join(root, ".env.local");

let out;
try {
  out = execSync("supabase status -o env", { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
} catch {
  console.error("Local Supabase is not running. Start it with `npm run db:start` (needs Docker), then run `npm run env:local`.");
  process.exit(1);
}

const s = {};
for (const line of out.split("\n")) {
  const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
  if (m) s[m[1]] = m[2].replace(/^"(.*)"$/, "$1");
}

// Supabase CLI name -> the name this app reads (.env.example documents each one).
const values = {
  DATABASE_URL: s.DB_URL,
  SUPABASE_URL: s.API_URL,
  SUPABASE_SECRET_KEY: s.SECRET_KEY || s.SERVICE_ROLE_KEY,
  VITE_SUPABASE_URL: s.API_URL,
  VITE_SUPABASE_PUBLISHABLE_KEY: s.PUBLISHABLE_KEY || s.ANON_KEY,
};
const missing = Object.entries(values).filter(([, v]) => !v).map(([k]) => k);
if (missing.length) {
  console.error(`supabase status did not report a value for: ${missing.join(", ")}. Is the Supabase CLI up to date?`);
  process.exit(1);
}

const kept = existsSync(file)
  ? readFileSync(file, "utf8").split("\n").filter((l) => {
      const k = l.match(/^([A-Z0-9_]+)=/)?.[1];
      return l.trim() && !l.startsWith("# Generated by") && !(k && k in values);
    })
  : [];
const body = [
  "# Generated by `npm run env:local` from `supabase status`. Local development values only; safe to regenerate.",
  ...Object.entries(values).map(([k, v]) => `${k}=${v}`),
  ...kept,
  "",
].join("\n");
writeFileSync(file, body, { mode: 0o600 });
console.log(`Wrote ${Object.keys(values).join(", ")} to ${path.relative(process.cwd(), file) || file}`);
